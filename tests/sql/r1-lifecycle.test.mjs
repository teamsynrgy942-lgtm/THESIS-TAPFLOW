async function originalRows(db) {
  return (await db.query(`
    select id::text, detected_at::text, room_id, code, status, evidence,
           resolved_at::text, updated_at::text, private_confidential
    from public.tapflow_r1_alerts order by id
  `)).rows;
}

async function alertAccess(db) {
  return (await db.query(`
    select c.relrowsecurity,
      has_table_privilege('authenticated', c.oid, 'SELECT') as can_select,
      has_table_privilege('authenticated', c.oid, 'INSERT') as can_insert,
      has_table_privilege('authenticated', c.oid, 'UPDATE') as can_update,
      has_table_privilege('authenticated', c.oid, 'DELETE') as can_delete,
      (select jsonb_agg(to_jsonb(p) order by p.policyname) from pg_policies p
       where p.schemaname = 'public' and p.tablename = 'tapflow_r1_alerts') as policies
    from pg_class c where c.oid = 'public.tapflow_r1_alerts'::regclass
  `)).rows[0];
}

async function expectDbError(db, action, code) {
  // A rejected statement aborts its transaction. Restore it before further checks.
  await db.exec('savepoint expected_failure');
  try {
    await assert.rejects(action, (error) => error.code === code,
      `Expected PostgreSQL error ${code}.`);
  } finally {
    await db.exec('rollback to savepoint expected_failure; release savepoint expected_failure');
  }
}

async function asRole(db, role, actor, action) {
  assert.ok(['anon', 'authenticated', 'service_role'].includes(role));
  await db.query("select set_config('request.jwt.claim.sub', $1, true)", [actor ?? '']);
  await db.exec(`set local role ${role}`);
  try { return await action(); }
  finally { await db.exec('reset role'); }
}

async function approve(db, ...actors) {
  for (const actor of actors) {
    await db.query('insert into tapflow_private.r1_staff(user_id) values ($1::uuid)', [actor]);
  }
}

async function observedAt(db, room, seconds) {
  // Logical timestamps exercise transition ordering only. The absent detector
  // adapter, not these private callbacks, must establish real-world freshness.
  return (await db.query(`
    select (migration_floor + $2::integer * interval '1 second')::text as observed
    from tapflow_private.r1_episodes where room_id = $1
  `, [room, seconds])).rows[0].observed;
}

async function fault(db, room, observed, evidence = { fixture: 'new observation' }) {
  return (await db.query(`
    select tapflow_private.r1_record_fault($1, $2::timestamptz, $3::jsonb)::text as id
  `, [room, observed, JSON.stringify(evidence)])).rows[0].id;
}

async function recover(db, room, observed) {
  return (await db.query(`
    select tapflow_private.r1_record_recovery($1, $2::timestamptz) as recovered
  `, [room, observed])).rows[0].recovered;
}

async function ledger(db, room) {
  return (await db.query(`
    select room_id, incident_id::text, migration_floor::text,
           last_fault_at::text, recovered_at::text
    from tapflow_private.r1_episodes where room_id = $1
  `, [room])).rows[0];
}

async function resolve(db, id) {
  return (await db.query('select public.tapflow_resolve_r1_incident($1) as incident', [id])).rows[0].incident;
}

describe('unmodified draft deployment guard', () => {
  let db;
  before(async () => { db = new PGlite(); await db.exec(fixture); });
  after(async () => { await db?.close(); });

  test('refuses installation and rolls back without changing original data or permissions', async () => {
    const rows = await originalRows(db);
    const access = await alertAccess(db);
    await assert.rejects(() => db.exec(draft), (error) => error.code === 'P0001'
      && /installed detector\/trigger baseline and adapter required/.test(error.message));
    await db.exec('rollback');
    assert.deepEqual(await originalRows(db), rows);
    assert.deepEqual(await alertAccess(db), access);
    assert.equal((await db.query("select to_regnamespace('tapflow_private') as schema")).rows[0].schema, null);
    assert.equal((await db.query(`
      select count(*)::integer as added from information_schema.columns
      where table_schema = 'public' and table_name = 'tapflow_r1_alerts'
        and column_name in ('last_detected_at', 'resolved_by')
    `)).rows[0].added, 0);
  });
});

describe('synthetic lifecycle infrastructure with baseline guard removed only in memory', () => {
  let db;
  let rowsBefore;
  let accessBefore;
  before(async () => {
    db = new PGlite();
    await db.exec(fixture);
    rowsBefore = await originalRows(db);
    accessBefore = await alertAccess(db);
    await db.exec(syntheticCore);
  });
  beforeEach(async () => { await db.exec('begin'); });
  afterEach(async () => { await db.exec('rollback'); });
  after(async () => { await db?.close(); });

  test('preserves historical fields and UPDATE-trigger timestamps without backfill or broader table access', async () => {
    assert.deepEqual(await originalRows(db), rowsBefore);
    assert.deepEqual(await alertAccess(db), accessBefore);
    const added = (await db.query(`
      select id::text, last_detected_at, resolved_by from public.tapflow_r1_alerts order by id
    `)).rows;
    assert.ok(added.every((row) => row.last_detected_at === null && row.resolved_by === null));
    assert.equal((await db.query('select count(*)::integer as count from tapflow_private.r1_staff')).rows[0].count, 0);
    assert.deepEqual((await db.query(`
      select relname, relrowsecurity from pg_class
      where oid in ('tapflow_private.r1_staff'::regclass, 'tapflow_private.r1_episodes'::regclass)
      order by relname
    `)).rows, [
      { relname: 'r1_episodes', relrowsecurity: true },
      { relname: 'r1_staff', relrowsecurity: true },
    ]);
  });

  test('read-only baseline export executes against catalogs, fingerprints definitions, and omits application rows and claims', async () => {
    const rowSecret = 'synthetic-row-value-never-part-of-the-schema';
    const claimSecret = 'synthetic-session-claim-never-part-of-the-schema';
    await db.query('update public.tapflow_r1_alerts set private_confidential = $1 where id = $2::bigint', [rowSecret, ids.active]);
    await db.query("select set_config('request.jwt.claims', $1, true)", [claimSecret]);
    const { rows } = await db.query(baselineExport);
    assert.equal(rows.length, 1);
    const result = rows[0].r1_lifecycle_baseline;
    assert.equal(result.format_version, 1);
    assert.equal(result.requested_inputs.length, 3);
    assert.ok(result.requested_inputs.every((input) => input.exists === true));
    assert.ok(result.functions.some((fn) => fn.name === 'r1_record_fault' && fn.r1_candidate));
    assert.ok(result.functions.some((fn) => fn.name === 'tapflow_can_resolve_r1' && fn.staff_candidate));
    for (const fn of result.functions) {
      assert.equal(fn.definition_md5, createHash('md5').update(fn.definition).digest('hex'));
      assert.ok(fn.identity);
      assert.ok(Array.isArray(fn.grants));
    }
    const trigger = result.triggers.find((item) => item.name === 'fixture_touch_updated_at');
    assert.ok(trigger);
    assert.equal(trigger.definition_md5, createHash('md5').update(trigger.definition).digest('hex'));
    assert.equal(trigger.function_definition_md5, createHash('md5').update(trigger.function_definition).digest('hex'));
    const alerts = result.tables.find((table) => table.schema === 'public' && table.table === 'tapflow_r1_alerts');
    assert.ok(alerts.rls_enabled);
    assert.ok(alerts.columns.some((column) => column.column_name === 'detected_at'));
    assert.ok(alerts.constraints.some((constraint) => constraint.type === 'p'));
    assert.ok(alerts.indexes.length > 0);
    assert.ok(alerts.policies.some((policy) => policy.policyname === 'fixture_read'));
    assert.ok(alerts.table_grants.some((grant) => grant.grantee === 'authenticated' && grant.privilege_type === 'SELECT'));
    assert.ok(result.tables.some((table) => table.schema === 'tapflow_private' && table.table === 'r1_staff' && table.staff_candidate));
    assert.deepEqual(result.realtime_publication, []);
    const serialized = JSON.stringify(result);
    for (const confidential of [rowSecret, claimSecret, 'original active evidence', 'original resolved evidence', users.first]) {
      assert.equal(serialized.includes(confidential), false);
    }
  });

  test('seeds both ACTIVE and RESOLVED latest incidents conservatively, retaining older open history', async () => {
    assert.equal((await ledger(db, 1)).incident_id, ids.active);
    assert.equal((await ledger(db, 2)).incident_id, ids.resolved);
    assert.equal((await ledger(db, 3)).incident_id, null);
    for (const room of [1, 2]) {
      const current = await ledger(db, room);
      assert.equal(await recover(db, room, current.migration_floor), false);
      assert.equal((await ledger(db, room)).incident_id, current.incident_id);
    }
    assert.equal((await db.query('select status from public.tapflow_r1_alerts where id = $1::bigint', [ids.olderOpen])).rows[0].status, 'ACTIVE');
  });

  test('repeated fault observations update Last detected on one incident monotonically', async () => {
    const second = await observedAt(db, 1, 2);
    const first = await observedAt(db, 1, 1);
    assert.equal(await fault(db, 1, first), ids.active);
    assert.equal(await fault(db, 1, second), ids.active);
    assert.equal(await fault(db, 1, first), ids.active);
    const alert = (await db.query(`
      select last_detected_at = $2::timestamptz as latest, detected_at::text, evidence
      from public.tapflow_r1_alerts where id = $1::bigint
    `, [ids.active, second])).rows[0];
    assert.equal(alert.latest, true);
    assert.equal(alert.detected_at, rowsBefore.find((row) => row.id === ids.active).detected_at);
    assert.deepEqual(alert.evidence, { fixture: 'original active evidence' });
    assert.equal((await db.query('select count(*)::integer as count from public.tapflow_r1_alerts')).rows[0].count, rowsBefore.length);
  });

  test('server resolution records staff and server time once, returns exact bigint ID and only public alert fields', async () => {
    await approve(db, users.first, users.second);
    const before = await ledger(db, 1);
    const serverStart = (await db.query('select clock_timestamp() as now')).rows[0].now;
    const first = await asRole(db, 'authenticated', users.first, () => resolve(db, ids.active));
    assert.equal(first.id, ids.active);
    assert.equal(typeof first.id, 'string');
    assert.equal(first.status, 'RESOLVED');
    assert.equal(first.resolved_by, users.first);
    assert.ok(Date.parse(first.resolved_at) >= new Date(serverStart).getTime());
    assert.ok(!Object.hasOwn(first, 'private_confidential'));
    assert.ok(!JSON.stringify(first).includes('synthetic-private-column'));
    assert.deepEqual(Object.keys(first).sort(), [
      'id', 'detected_at', 'room_id', 'code', 'status', 'evidence',
      'resolved_at', 'last_detected_at', 'resolved_by',
    ].sort());
    const second = await asRole(db, 'authenticated', users.second, () => resolve(db, ids.active));
    assert.deepEqual(second, first);
    assert.deepEqual(await ledger(db, 1), before);
    assert.equal((await db.query('select status from public.tapflow_r1_alerts where id = $1::bigint', [ids.olderOpen])).rows[0].status, 'ACTIVE');
  });

  test('staff resolution alone does not rearm: repeated faults stay on that resolved incident', async () => {
    await approve(db, users.first);
    const closed = await asRole(db, 'authenticated', users.first, () => resolve(db, ids.active));
    const time = await observedAt(db, 1, 1);
    assert.equal(await fault(db, 1, time), ids.active);
    const current = (await db.query(`
      select status, resolved_at = $2::timestamptz as same_time, resolved_by::text,
             last_detected_at = $3::timestamptz as detected
      from public.tapflow_r1_alerts where id = $1::bigint
    `, [ids.active, closed.resolved_at, time])).rows[0];
    assert.deepEqual(current, { status: 'RESOLVED', same_time: true, resolved_by: users.first, detected: true });
    assert.equal((await ledger(db, 1)).incident_id, ids.active);
    assert.equal((await db.query('select count(*)::integer as count from public.tapflow_r1_alerts')).rows[0].count, rowsBefore.length);
  });

  test('legacy resolved incidents remain the current episode until a new recovery is confirmed', async () => {
    const time = await observedAt(db, 2, 1);
    assert.equal(await fault(db, 2, time), ids.resolved);
    await approve(db, users.first);
    const result = await asRole(db, 'authenticated', users.first, () => resolve(db, ids.resolved));
    assert.equal(result.status, 'RESOLVED');
    assert.equal(result.resolved_by, null);
    assert.equal(Date.parse(result.resolved_at), Date.parse('2026-01-02T02:00:00Z'));
    assert.equal((await ledger(db, 2)).incident_id, ids.resolved);
  });

  test('recovery requires a newer observation watermark and changes only that room', async () => {
    const otherRoom = await ledger(db, 2);
    const faultTime = await observedAt(db, 1, 2);
    await fault(db, 1, faultTime);
    assert.equal(await recover(db, 1, await observedAt(db, 1, 1)), false);
    assert.equal(await recover(db, 1, faultTime), false);
    assert.equal((await ledger(db, 1)).incident_id, ids.active);
    const newer = await observedAt(db, 1, 3);
    assert.equal(await recover(db, 1, newer), true);
    assert.equal((await ledger(db, 1)).incident_id, null);
    assert.equal(await recover(db, 1, newer), false);
    assert.deepEqual(await ledger(db, 2), otherRoom);
    assert.equal((await db.query('select status from public.tapflow_r1_alerts where id = $1::bigint', [ids.active])).rows[0].status, 'ACTIVE');
  });

  test('a later fault starts a new incident after recovery while the older incident remains open', async () => {
    await fault(db, 1, await observedAt(db, 1, 1));
    assert.equal(await recover(db, 1, await observedAt(db, 1, 2)), true);
    const newId = await fault(db, 1, await observedAt(db, 1, 3));
    assert.notEqual(newId, ids.active);
    assert.equal((await ledger(db, 1)).incident_id, newId);
    assert.equal(await fault(db, 1, await observedAt(db, 1, 4)), newId);
    const open = (await db.query(`
      select id::text, status from public.tapflow_r1_alerts
      where room_id = 1 and code = 'R1_MISSING_FLOW_SIGNAL' order by id
    `)).rows;
    assert.deepEqual(open, [{ id: ids.active, status: 'ACTIVE' }, { id: newId, status: 'ACTIVE' }]);
  });

  test('a delayed fault from before recovery cannot reopen or create the next episode', async () => {
    const oldFault = await observedAt(db, 1, 1);
    await fault(db, 1, oldFault);
    const recovery = await observedAt(db, 1, 2);
    await recover(db, 1, recovery);
    assert.equal(await fault(db, 1, oldFault), null);
    assert.equal(await fault(db, 1, recovery), null);
    assert.equal((await ledger(db, 1)).incident_id, null);
    assert.equal((await db.query('select count(*)::integer as count from public.tapflow_r1_alerts')).rows[0].count, rowsBefore.length);
  });

  test('a first fault for a room with no R1 history creates one incident without changing another rule', async () => {
    const newId = await fault(db, 3, await observedAt(db, 3, 1));
    assert.notEqual(newId, ids.otherRule);
    assert.equal(await fault(db, 3, await observedAt(db, 3, 2)), newId);
    const other = (await db.query('select id::text, code, status from public.tapflow_r1_alerts where id = $1::bigint', [ids.otherRule])).rows[0];
    assert.deepEqual(other, { id: ids.otherRule, code: 'ANOTHER_RULE', status: 'ACTIVE' });
    assert.equal((await ledger(db, 1)).incident_id, ids.active);
  });

  test('capability requires enabled server membership; metadata labels do not grant staff authority', async () => {
    await asRole(db, 'authenticated', users.ordinary, async () => {
      await db.query("select set_config('request.jwt.claims', $1, true)", [JSON.stringify({
        user_metadata: { role: 'staff', admin: true }, app_metadata: { role: 'staff' }, role: 'staff',
      })]);
      assert.equal((await db.query('select public.tapflow_can_resolve_r1() as allowed')).rows[0].allowed, false);
      await expectDbError(db, () => resolve(db, ids.active), '42501');
    });
    await approve(db, users.first);
    await asRole(db, 'authenticated', users.first, async () => {
      assert.equal((await db.query('select public.tapflow_can_resolve_r1() as allowed')).rows[0].allowed, true);
    });
    await db.query('update tapflow_private.r1_staff set enabled = false where user_id = $1::uuid', [users.first]);
    await asRole(db, 'authenticated', users.first, async () => {
      assert.equal((await db.query('select public.tapflow_can_resolve_r1() as allowed')).rows[0].allowed, false);
      await expectDbError(db, () => resolve(db, ids.active), '42501');
    });
    await asRole(db, 'authenticated', null, async () => {
      assert.equal((await db.query('select public.tapflow_can_resolve_r1() as allowed')).rows[0].allowed, false);
      await expectDbError(db, () => resolve(db, ids.active), '42501');
    });
  });

  test('private callbacks and ledger remain inaccessible to clients, including service_role and approved staff', async () => {
    await approve(db, users.first);
    const at = await observedAt(db, 1, 1);
    for (const role of ['anon', 'authenticated', 'service_role']) {
      const privileges = (await db.query(`
        select has_schema_privilege($1, 'tapflow_private', 'USAGE') as schema_usage,
          has_function_privilege($1, 'tapflow_private.r1_lock_room(integer)', 'EXECUTE') as lock_room,
          has_function_privilege($1, 'tapflow_private.r1_record_fault(integer,timestamptz,jsonb)', 'EXECUTE') as fault,
          has_function_privilege($1, 'tapflow_private.r1_record_recovery(integer,timestamptz)', 'EXECUTE') as recovery
      `, [role])).rows[0];
      assert.deepEqual(privileges, { schema_usage: false, lock_room: false, fault: false, recovery: false });
      await asRole(db, role, users.first, async () => {
        await expectDbError(db, () => fault(db, 1, at), '42501');
        await expectDbError(db, () => recover(db, 1, at), '42501');
        await expectDbError(db, () => db.query('select tapflow_private.r1_lock_room(1)'), '42501');
        await expectDbError(db, () => db.query('select * from tapflow_private.r1_episodes'), '42501');
        if (role !== 'authenticated') await expectDbError(db, () => resolve(db, ids.active), '42501');
      });
    }
  });

  test('resolution rejects invalid, missing, and unrelated-rule IDs without changing alerts', async () => {
    await approve(db, users.first);
    const before = await originalRows(db);
    await asRole(db, 'authenticated', users.first, async () => {
      for (const invalid of [null, '', '0', '-1', '1.2', 'not-an-id', '01']) {
        await expectDbError(db, () => resolve(db, invalid), '22023');
      }
      await expectDbError(db, () => resolve(db, '9223372036854775807'), 'P0002');
      await expectDbError(db, () => resolve(db, ids.otherRule), 'P0002');
    });
    assert.deepEqual(await originalRows(db), before);
  });
});
